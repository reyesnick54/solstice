#!/usr/bin/env node
// Zero-dependency build for the SunRey desktop dashboard.
//
// Copies src/ to dist/ and writes the environment-specific runtime config and
// security headers. Cloudflare Pages: build command `node apps/dashboard/build.mjs`,
// output directory `apps/dashboard/dist`.
//
// Environment (all optional; production defaults shown):
//   SUNREY_DASHBOARD_API_BASE       https://api.sunrey.xyz
//   SUNREY_DASHBOARD_EXPLORER_URL   (empty: explorer links hidden)
//   SUNREY_DASHBOARD_ENV_LABEL      Sandbox
//   CF_PAGES_COMMIT_SHA / GITHUB_SHA  release id shown in Settings

import { cpSync, mkdirSync, rmSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src');
const out = join(here, 'dist');

function origin(url) {
  try {
    return new URL(url).origin;
  } catch {
    throw new Error(`SUNREY_DASHBOARD_API_BASE is not a valid URL: ${url}`);
  }
}

const apiBase = (process.env.SUNREY_DASHBOARD_API_BASE || 'https://api.sunrey.xyz').replace(/\/+$/, '');
const explorerUrl = (process.env.SUNREY_DASHBOARD_EXPLORER_URL || '').replace(/\/+$/, '');
const environmentLabel = process.env.SUNREY_DASHBOARD_ENV_LABEL || 'Sandbox';
const release = (process.env.CF_PAGES_COMMIT_SHA || process.env.GITHUB_SHA || process.env.RENDER_GIT_COMMIT || 'local').slice(0, 12);
const apiOrigin = origin(apiBase);
if (!apiOrigin.startsWith('https://') && !/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/.test(apiOrigin)) {
  throw new Error('The dashboard API must be https (or a local http origin for development).');
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(src, out, { recursive: true });

const config = {
  apiBase,
  explorerUrl,
  environmentLabel,
  release,
  builtAt: new Date().toISOString(),
};
writeFileSync(
  join(out, 'js', 'config.js'),
  `// Generated by build.mjs. Do not edit.\nexport const CONFIG = Object.freeze(${JSON.stringify(config, null, 2)});\n`,
);

const csp = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self' https://fonts.googleapis.com",
  "style-src-attr 'unsafe-inline'",
  "font-src https://fonts.gstatic.com",
  "img-src 'self' data:",
  `connect-src ${apiOrigin}`,
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

writeFileSync(
  join(out, '_headers'),
  `/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin
  X-Frame-Options: DENY
  Strict-Transport-Security: max-age=63072000; includeSubDomains
  X-Robots-Tag: noindex, nofollow

/index.html
  Cache-Control: no-store

/js/*
  Cache-Control: no-cache

/assets/*
  Cache-Control: public, max-age=86400
`,
);

// Single-page app: every unknown path serves index.html.
writeFileSync(join(out, '_redirects'), '/*    /index.html   200\n');

function size(dir) {
  return readdirSync(dir).reduce((sum, name) => {
    const p = join(dir, name);
    const s = statSync(p);
    return sum + (s.isDirectory() ? size(p) : s.size);
  }, 0);
}
console.log(JSON.stringify({ built: out, apiBase, explorerUrl: explorerUrl || null, environmentLabel, release, bytes: size(out) }));
