export function listSuites() {
  return Object.keys(TEST_SUITES).sort();
}

export function globsForSuite(name) {
  const globs = TEST_SUITES[name];
  if (!globs || globs.length === 0) {
    throw new Error(`Unknown or empty test suite: ${name}`);
  }
  return globs;
}

export function runRepositoryTests(suite = 'unit', options = {}) {
  const globs = globsForSuite(suite);
  const args = ['node', ...NODE_ARGS, ...globs];
  const result = spawnSync(args[0], args.slice(1), {
    cwd: options.cwd ?? ROOT,
    stdio: options.stdio ?? 'inherit',
    env: options.env ?? process.env,
  });
  return result.status ?? 1;
}

function usage() {
  console.error('Usage: node scripts/run-repository-tests.mjs [suite]');
  console.error('Suites:', listSuites().join(', '));
}

function main() {
  const suite = process.argv[2] ?? 'unit';
  if (suite === '--list') {
    console.log(listSuites().join('\n'));
    return;
  }
  if (suite === '--help' || suite === '-h') {
    usage();
    return;
  }
  let globs;
  try {
    globs = globsForSuite(suite);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    usage();
    process.exit(1);
  }
  const status = runRepositoryTests(suite);
  process.exit(status);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
