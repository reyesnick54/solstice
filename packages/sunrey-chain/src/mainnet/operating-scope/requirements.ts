/**
 * Evidence requirements per activation domain.
 * Missing evidence disables the row. No permissive defaults.
 */

import type { ActivationDomain } from '../types.ts';
import type { ScopeEvidenceClass, ScopeRequirement } from './types.ts';

function req(
  requirementId: string,
  activationDomain: ActivationDomain,
  evidenceClass: ScopeEvidenceClass,
  extra: Partial<Pick<ScopeRequirement, 'hinOnly' | 'productiveUseRight' | 'corridorEndpoint'>> = {},
): ScopeRequirement {
  return Object.freeze({
    requirementId,
    activationDomain,
    evidenceClass,
    blocking: true,
    ...extra,
  });
}

