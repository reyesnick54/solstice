export function requirementsFor(domain: ActivationDomain): readonly ScopeRequirement[] {
  return SCOPE_REQUIREMENTS.filter((row) => row.activationDomain === domain);
}

export function reasonCodeForClass(
  evidenceClass: ScopeEvidenceClass,
): import('./types.ts').OperatingScopeReasonCode {
  switch (evidenceClass) {
    case 'LICENSE_OR_REGISTRATION':
      return 'LICENSE_EVIDENCE_MISSING';
    case 'COUNSEL_OPINION':
      return 'COUNSEL_EVIDENCE_MISSING';
    case 'REGULATORY_APPROVAL':
      return 'REGULATORY_APPROVAL_MISSING';
    case 'PARTNER_AGREEMENT':
      return 'PARTNER_AGREEMENT_MISSING';
    case 'PRIVACY_REVIEW':
      return 'PRIVACY_REVIEW_MISSING';
    case 'DATA_RESIDENCY':
      return 'DATA_RESIDENCY_EVIDENCE_MISSING';
    case 'CONSENT_CONTROL':
      return 'CONSENT_EVIDENCE_MISSING';
    case 'PURPOSE_CONTROL':
      return 'PURPOSE_CONTROL_EVIDENCE_MISSING';
    case 'TERMS_AGREEMENT':
      return 'TERMS_AGREEMENT_MISSING';
    case 'DATA_LICENSE':
    case 'JURISDICTIONAL_USE_RIGHT':
    case 'PROVIDER_CONTRACT':
      return 'DATA_RIGHTS_EVIDENCE_MISSING';
    case 'SOURCE_CERTIFICATION':
      return 'SOURCE_CERTIFICATION_MISSING';
    case 'HUMAN_AUTHORIZATION':
      return 'HUMAN_APPROVAL_REQUIRED';
    default:
      return 'PROVIDER_NOT_ELIGIBLE';
  }
}
