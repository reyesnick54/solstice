/**
 * HELIOS HEALTH06 — engineering baseline V2 qualification (fast CI).
 */

import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { describe, it } from 'node:test';

import { LIVE_TRADING_ENABLED } from '../packages/config/src/flags.ts';
import {
  HELIOS_ENGINEERING_BASELINE_V2_BLOCKED,
  HELIOS_ENGINEERING_BASELINE_V2_QUALIFIED,
  evaluateEngineeringBaselineQualification,
  evaluateHeliosStrictScopedTypecheck,
  renderEngineeringBaselineMarkdown,
  type EngineeringBaselineGateResult,
} from '../packages/platform/src/helios/hardening/index.ts';

const ROOT = process.cwd();
const BASELINE_DOC = join(ROOT, 'docs/helios/hardening/HELIOS_ENGINEERING_BASELINE_V2.md');

function allMandatoryGatesPass(): EngineeringBaselineGateResult[] {
  const ids = [
    'normal_ci',
    'helios_release_candidate',
    'helios_strict_scoped_typecheck',
    'architecture_lint',
    'production_safety',
    'aaf_v2_qualification',
    'earn01_earn12_qualification',
    'native_assimilation_qualification',
    'strategy_lab',
    'execution_twin',
    'agent_permissions',
    'provider_conformance',
    'database_migrations',
    'fuzz_extended',
    'formal_extended',
    'bench_nightly',
    'memory_soak',
    'restart_recovery',
    'live_trading_disabled',
    'production_authorized_disabled',
  ] as const;
  return ids.map((gateId) => Object.freeze({ gateId, pass: true, detail: 'fixture' }));
}

describe('HELIOS HEALTH06 — engineering baseline V2', () => {
  it('LIVE_TRADING_ENABLED remains false', () => {
    assert.equal(LIVE_TRADING_ENABLED, false);
  });

  it('evaluates HELIOS strict scoped typecheck helper', () => {
    const ok = evaluateHeliosStrictScopedTypecheck('error TS2304: packages/platform/src/helios/x.ts');
    assert.equal(ok.pass, false);
    const clean = evaluateHeliosStrictScopedTypecheck('error TS2304: packages/unrelated/x.ts');
    assert.equal(clean.pass, true);
  });

  it('emits HELIOS_ENGINEERING_BASELINE_V2_QUALIFIED only when all mandatory gates pass', () => {
    const qualified = evaluateEngineeringBaselineQualification({
      root: ROOT,
      gitSha: 'a'.repeat(40),
      evaluatedAt: '2026-11-04T00:00:00.000Z',
      gates: allMandatoryGatesPass(),
    });
    assert.equal(qualified.marker, HELIOS_ENGINEERING_BASELINE_V2_QUALIFIED);
    assert.equal(qualified.qualified, true);
    assert.equal(qualified.blockers.length, 0);
  });

  it('blocks when a mandatory gate fails', () => {
    const gates = allMandatoryGatesPass().map((row) =>
      row.gateId === 'fuzz_extended' ? { ...row, pass: false, detail: 'simulated fail' } : row,
    );
    const result = evaluateEngineeringBaselineQualification({
      root: ROOT,
      gitSha: 'b'.repeat(40),
      evaluatedAt: '2026-11-04T00:00:00.000Z',
      gates,
    });
    assert.equal(result.marker, HELIOS_ENGINEERING_BASELINE_V2_BLOCKED);
    assert.ok(result.blockers.some((line) => line.includes('fuzz_extended')));
  });

  it('baseline markdown doc is generated by the HEALTH06 runner', () => {
    if (!existsSync(BASELINE_DOC)) {
      assert.fail('run npm run helios:health06:qualify to generate docs/helios/hardening/HELIOS_ENGINEERING_BASELINE_V2.md');
    }
    const md = renderEngineeringBaselineMarkdown(
      evaluateEngineeringBaselineQualification({
        root: ROOT,
        gitSha: 'c'.repeat(40),
        evaluatedAt: '2026-11-04T00:00:00.000Z',
        gates: allMandatoryGatesPass(),
      }),
    );
    assert.match(md, /HELIOS Engineering Baseline V2/);
    assert.match(md, /type safety|type_safety/i);
  });
});
